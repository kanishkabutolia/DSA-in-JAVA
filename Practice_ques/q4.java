public class q4 {
    public static void main (String[] args){
        //Calculate volume of sphere with given radius

        double radius = 6.39;
        double pi = 3.14;
        double volume = ((double)4/3)*pi*radius*radius*radius;

        System.out.printf("Volume of Sphere with the radius = %.2f is : %.2f", radius, volume);
    }
    
}
